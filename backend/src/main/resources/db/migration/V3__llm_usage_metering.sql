CREATE TABLE llm_usage_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    execution_id UUID NOT NULL UNIQUE,
    task_id BIGINT NOT NULL REFERENCES ai_task(id),
    provider_code VARCHAR(64) NOT NULL,
    model_name VARCHAR(128) NOT NULL,
    input_tokens BIGINT CHECK (input_tokens IS NULL OR input_tokens >= 0),
    output_tokens BIGINT CHECK (output_tokens IS NULL OR output_tokens >= 0),
    cached_input_tokens BIGINT CHECK (cached_input_tokens IS NULL OR cached_input_tokens >= 0),
    model_call_count BIGINT NOT NULL CHECK (model_call_count >= 0),
    llm_duration_ms BIGINT NOT NULL CHECK (llm_duration_ms >= 0),
    measurement_status VARCHAR(16) NOT NULL CHECK (measurement_status IN ('COMPLETE', 'PARTIAL', 'UNAVAILABLE')),
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_llm_usage_task_recorded ON llm_usage_record(task_id, recorded_at DESC);
